import { readFile, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
import { createRequire } from "node:module";
import polygonClipping from "polygon-clipping";
import { pointOnFeature } from "@turf/point-on-feature";
const root = new URL("../", import.meta.url);
const mobileRequire = createRequire(new URL("apps/mobile/package.json", root));
const { toMercator } = mobileRequire("@turf/projection");
const sourcePath = "data/maps/source/geoBoundaries-CHN-ADM1-2019-simplified.geojson";
const source = await readFile(new URL(sourcePath, root));
const sha256 = createHash("sha256").update(source).digest("hex");
if (sha256 !== "bc4afc7eacf4351ae5b3ae7a612327987ce1123cb5deb8574fb49107091c6623")
  throw new Error("geographic_source_integrity_failed");
const original = JSON.parse(source);
const legacy = JSON.parse(await readFile(new URL("data/maps/china-districts.json", root)));
const properties = new Map(legacy.provinces.map((shape) => [shape.sourceFeatureId, shape]));
const geojson = {
  type: "FeatureCollection",
  features: original.features.map((feature) => {
    const shape = properties.get(feature.properties.shapeID);
    if (!shape) throw new Error("geographic_province_mapping_missing");
    return {
      type: "Feature",
      properties: {
        id: shape.id,
        name: shape.sourceName,
        province: shape.province,
        labelPoint: pointOnFeature(feature).geometry.coordinates,
      },
      geometry: feature.geometry,
    };
  }),
};
const projected = geojson.features.map((feature) => {
  const geometry = toMercator(feature).geometry;
  return {
    ...feature.properties,
    polygons: geometry.type === "MultiPolygon" ? geometry.coordinates : [geometry.coordinates],
  };
});
const points = projected.flatMap((feature) => feature.polygons.flat(2));
const bounds = points.reduce(
  (b, [x, y]) => ({
    minX: Math.min(b.minX, x),
    maxX: Math.max(b.maxX, x),
    minY: Math.min(b.minY, -y),
    maxY: Math.max(b.maxY, -y),
  }),
  { minX: Infinity, maxX: -Infinity, minY: Infinity, maxY: -Infinity }
);
const width = 1000,
  height = 800,
  margin = 48;
const scale = Math.min(
  (width - 2 * margin) / (bounds.maxX - bounds.minX),
  (height - 2 * margin) / (bounds.maxY - bounds.minY)
);
const fit = {
  scale,
  tx: (width - (bounds.maxX + bounds.minX) * scale) / 2,
  ty: (height - (bounds.maxY + bounds.minY) * scale) / 2,
};
const fmt = (v) => Number(v.toFixed(4));
const path = (polygons) =>
  polygons
    .flatMap((polygon) =>
      polygon.map(
        (ring) =>
          "M " +
          ring
            .map(([x, y]) => `${fmt(x * scale + fit.tx)} ${fmt(-y * scale + fit.ty)}`)
            .join(" L ") +
          " Z"
      )
    )
    .join(" ");
const outline = path(polygonClipping.union(...projected.map((feature) => feature.polygons)));
const shapes = projected.map(({ polygons, labelPoint, ...shape }) => ({
  ...shape,
  d: path(polygons),
}));
const meta = {
  projection: "EPSG:3857",
  source: sourcePath,
  sourceSha256: sha256,
  featureCount: geojson.features.length,
  viewBox: { width, height },
  bounds,
  fit,
};
const module = `// Generated by scripts/generate-geographic-map.mjs. Do not edit.\nimport type { FeatureCollection, Polygon, MultiPolygon } from "geojson";\nexport const CHINA_GEOGRAPHIC_META = ${JSON.stringify(meta)};\nexport const CHINA_GEOGRAPHIC_GEOJSON: FeatureCollection<Polygon | MultiPolygon> = ${JSON.stringify(geojson)};\nexport const CHINA_GEOGRAPHIC_OUTLINE_D = ${JSON.stringify(outline)};\nexport const CHINA_GEOGRAPHIC_SHAPES: {id:string;name:string;province:string|null;d:string}[] = ${JSON.stringify(shapes)};\n`;
await writeFile(new URL("apps/mobile/src/map/chinaGeographicData.ts", root), module);
const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="1000" height="800" viewBox="0 0 1000 800"><rect width="1000" height="800" fill="#eaf1f4"/><path d="${outline}" fill="#fafcfd" fill-rule="evenodd" stroke="#94aab5" stroke-width="1.6"/>${shapes.map((shape) => `<path d="${shape.d}" fill="none" stroke="#cad7dd" stroke-width="0.9"/>`).join("")}</svg>`;
await writeFile(new URL("data/maps/china-geographic-map.svg", root), svg);
console.log(JSON.stringify(meta));
