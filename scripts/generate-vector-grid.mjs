import { readFile, readdir, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";

const require = createRequire(import.meta.url);
const entry = require.resolve("leaflet.vectorgrid");
const root = dirname(dirname(entry));
const readme = await readFile(join(root, "README.md"), "utf8");
const notices = [readme.slice(readme.indexOf('"THE BEER-WARE LICENSE"'))];
const localRequire = createRequire(join(root, "package.json"));
for (const name of ["pbf", "vector-tile", "topojson-client", "whatwg-fetch"]) {
  const packageRoot = dirname(localRequire.resolve(name + "/package.json"));
  const filename = (await readdir(packageRoot)).find((name) =>
    /^LICENSE(?:\.(?:txt|md))?$/i.test(name)
  );
  if (!filename) throw new Error("missing_license:" + name);
  const license = await readFile(join(packageRoot, filename), "utf8");
  notices.push(name + "\n" + license);
}
// The prebuilt distribution also embeds geojson-vt 2.2.0 and point-geometry.
for (const name of ["geojson-vt", "point-geometry"]) {
  const packageRoot = dirname(require.resolve(name + "/package.json"));
  const filename = (await readdir(packageRoot)).find((name) =>
    /^LICENSE(?:\.(?:txt|md))?$/i.test(name)
  );
  if (!filename) {
    const metadata = JSON.parse(await readFile(join(packageRoot, "package.json"), "utf8"));
    if (
      name !== "point-geometry" ||
      metadata.license !== "ISC" ||
      metadata.author !== "Tom MacWright"
    )
      throw new Error("missing_license:" + name);
    notices.push(
      "point-geometry 0.0.0: ISC (declared in upstream package.json)\nCopyright Tom MacWright\n" +
        "Permission to use, copy, modify, and/or distribute this software for any purpose with or without fee is hereby granted, provided that the above copyright notice and this permission notice appear in all copies.\n" +
        'THE SOFTWARE IS PROVIDED "AS IS" AND THE AUTHOR DISCLAIMS ALL WARRANTIES WITH REGARD TO THIS SOFTWARE INCLUDING ALL IMPLIED WARRANTIES OF MERCHANTABILITY AND FITNESS. IN NO EVENT SHALL THE AUTHOR BE LIABLE FOR ANY SPECIAL, DIRECT, INDIRECT, OR CONSEQUENTIAL DAMAGES OR ANY DAMAGES WHATSOEVER RESULTING FROM LOSS OF USE, DATA OR PROFITS, WHETHER IN AN ACTION OF CONTRACT, NEGLIGENCE OR OTHER TORTIOUS ACTION, ARISING OUT OF OR IN CONNECTION WITH THE USE OR PERFORMANCE OF THIS SOFTWARE.'
    );
  } else notices.push(name + "\n" + (await readFile(join(packageRoot, filename), "utf8")));
}
const js = await readFile(entry, "utf8");
await writeFile(
  new URL("../apps/mobile/src/map/vendor/vectorGrid.ts", import.meta.url),
  "// Generated by scripts/generate-vector-grid.mjs; retain accompanying notices.\n" +
    "export const VECTOR_GRID_JS = " +
    JSON.stringify(js) +
    ";\n" +
    "export const VECTOR_GRID_NOTICES = " +
    JSON.stringify(notices.join("\n\n")) +
    ";\n"
);
await writeFile(
  new URL("../apps/mobile/src/map/vendor/VECTOR_GRID_LICENSES", import.meta.url),
  notices.join("\n\n")
);
console.log("Bundled Leaflet.VectorGrid 1.3.0 with license notices");
