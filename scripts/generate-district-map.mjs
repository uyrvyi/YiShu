import { readFile, writeFile, mkdir } from "node:fs/promises";
import { createHash } from "node:crypto";
import { createRequire } from "node:module";
import { pinyin } from "pinyin-pro";
import { pointOnFeature } from "@turf/point-on-feature";
import { booleanPointInPolygon } from "@turf/boolean-point-in-polygon";

const require = createRequire(import.meta.url);
const root = new URL("../", import.meta.url);
const source = await readFile(new URL(process.argv[2] ?? ".local/county-source.geojson", root));
const hash = createHash("sha256").update(source).digest("hex");
if (hash !== "ea64fe24f193e319ce48895f229a5b3f46d2a60f3f3df67e6172ab037e4cc8fd")
  throw new Error("county_source_integrity_failed");
const counties = JSON.parse(source.toString()).features;
const provinces = JSON.parse(
  await readFile(new URL("data/maps/source/geoBoundaries-CHN-ADM1-2019-simplified.geojson", root))
).features;
const regions = JSON.parse(
  await readFile(new URL("apps/mobile/src/regions/data/pca-code.json", root))
);
const transliterate = (name) =>
  pinyin(name, { toneType: "none", type: "array" }).join("").toLowerCase();
const englishKey = (name) =>
  name
    .toLowerCase()
    .replace(/(?:new )?(?:district|county|city)$/u, "")
    .replace(/[^a-z]/gu, "");
const chineseKey = (name) =>
  transliterate(name.replace(/(?:新区|自治县|自治旗|区|县|市|旗)$/u, ""));
const anchors = {};
const missing = [];
// Names in the pinned ADM1 source, including its historical Guangdong label typo.
const provinceNames = {
  15: "inner mongolia",
  44: "guangzhou",
  54: "tibet",
  61: "shaanxi",
  50: "chongqing",
};
const points = counties.map((feature) => ({ feature, point: pointOnFeature(feature) }));
for (const province of regions) {
  const prefix =
    provinceNames[province.code] ??
    transliterate(
      province.name.replace(/(?:壮族自治区|回族自治区|维吾尔自治区|自治区|省|市)$/u, "")
    );
  const boundary = provinces.find((feature) =>
    feature.properties.shapeName.toLowerCase().startsWith(prefix)
  );
  if (!boundary) throw new Error("province_not_matched:" + province.code);
  const candidates = points.filter(({ point }) => booleanPointInPolygon(point, boundary));
  for (const city of province.children ?? []) {
    for (const district of city.children ?? []) {
      const matches = candidates.filter(
        ({ feature }) => englishKey(feature.properties.shapeName) === chineseKey(district.name)
      );
      const cityName = ["11", "12", "31", "50"].includes(province.code) ? province.name : city.name;
      const key = [province.name, cityName, district.name].join("/");
      // Ambiguous or renamed districts are unavailable, never replaced with a city coordinate.
      if (matches.length !== 1) {
        missing.push({ key, code: district.code });
        continue;
      }
      const match = matches[0];
      const [lng, lat] = match.point.geometry.coordinates;
      anchors[key] = {
        code: district.code,
        province: province.name,
        city: cityName,
        district: district.name,
        x: Number((((lng + 180) / 360) * 1000).toFixed(6)),
        y: Number((((90 - lat) / 180) * 800).toFixed(6)),
        sourceShapeId: match.feature.properties.shapeID,
      };
    }
  }
}
const asset = {
  source: {
    provider: "geoBoundaries",
    revision: "9469f09",
    year: 2017,
    boundaryID: "CHN-ADM3-62558664",
    sha256: hash,
    license: "ODbL-1.0",
    releaseApproval: "pending",
    mapping: "unique transliteration within province; historical representative points",
  },
  anchors,
  missing,
};
await writeFile(new URL("data/maps/district-anchors.json", root), JSON.stringify(asset));
const leafletJS = await readFile(require.resolve("leaflet/dist/leaflet.js"), "utf8");
const leafletCSS = await readFile(require.resolve("leaflet/dist/leaflet.css"), "utf8");
await mkdir(new URL("apps/mobile/src/map/vendor/", root), { recursive: true });
await writeFile(
  new URL("apps/mobile/src/map/vendor/leaflet.ts", root),
  "// Generated by scripts/generate-district-map.mjs; Leaflet 1.9.4, BSD-2-Clause.\n" +
    "export const LEAFLET_JS = " +
    JSON.stringify(leafletJS) +
    ";\n" +
    "export const LEAFLET_CSS = " +
    JSON.stringify(leafletCSS) +
    ";\n"
);
await writeFile(
  new URL("apps/mobile/src/map/vendor/LEAFLET_LICENSE", root),
  await readFile(require.resolve("leaflet/LICENSE"))
);
console.log(
  JSON.stringify({
    anchors: Object.keys(anchors).length,
    missing: missing.length,
    shanghai: Object.entries(anchors).filter(([key]) => key.startsWith("上海")),
  })
);
